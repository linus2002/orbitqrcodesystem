#!/usr/bin/env node
/**
 * Generate the Sanity Studio schema from the application's data model.
 *
 *   npm run studio:schema
 *
 * src/db/schema.js is the single definition of every document type. The
 * Studio's schema is derived from it, never written by hand, so the two
 * cannot drift apart: change a field there, run this, and commit both.
 *
 * The Studio is a READ-ONLY window onto the data. Every field is read-only
 * and studio/sanity.config.js removes every document action, because a
 * record edited in the Studio would bypass what the application enforces on
 * every write - the audit trail, the lifecycle rules, the unique keys. Fields
 * marked `secret` (password hashes, pseudonymised IPs, CSRF tokens) are
 * hidden, and bookkeeping types are not listed at all.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { TYPES } from '../src/db/schema.js';

const ROOT = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const OUT = path.join(ROOT, 'studio', 'schemaTypes', 'generated.js');

/** What each document shows as its title and subtitle in lists. */
const PREVIEW = {
  user: ['full_name', 'email'],
  session: ['id', 'expires_at'],
  product: ['name', 'sku'],
  leaflet: ['version', 'language'],
  batch: ['batch_number', 'status'],
  code: ['code', 'status'],
  scan: ['code_text', 'result'],
  alert: ['title', 'status'],
  consumerReport: ['description', 'status'],
  shipment: ['reference', 'to_name'],
  auditLog: ['action', 'actor_email'],
  smsLog: ['direction', 'created_at'],
  setting: ['key', 'value'],
  verifier: ['full_name', 'phone'],
  leafletFile: ['filename', 'status'],
};

const title = (name) =>
  name.replace(/_/g, ' ').replace(/\b[a-z]/, (c) => c.toUpperCase()).replace(/\bid\b/i, 'ID');

function field(name, def) {
  const f = { name, title: title(name), readOnly: true };
  if (def.secret) f.hidden = true;
  switch (def.kind) {
    case 'string':
      f.type = 'string';
      break;
    case 'text':
    case 'json':
      f.type = 'text';
      f.rows = def.kind === 'json' ? 6 : 3;
      break;
    case 'int':
      f.type = 'number';
      break;
    case 'bool01':
      f.type = 'number';
      f.options = { list: [{ title: 'No', value: 0 }, { title: 'Yes', value: 1 }] };
      break;
    case 'date':
      f.type = 'date';
      break;
    case 'datetime':
      f.type = 'datetime';
      break;
    case 'array':
      f.type = 'array';
      f.of = [{
        type: 'object',
        name: `${name}Item`,
        fields: Object.entries(def.of).map(([n, kind]) => ({ name: n, title: title(n), type: kind, readOnly: true })),
        preview: { select: { title: Object.keys(def.of)[0] } },
      }];
      break;
    default:
      throw new Error(`no Studio mapping for field kind "${def.kind}"`);
  }
  if (def.enum && def.kind === 'string') f.options = { list: def.enum };
  return f;
}

const types = Object.entries(TYPES).map(([name, spec]) => {
  const [t, s] = PREVIEW[name] ?? ['id'];
  return {
    name,
    title: spec.title,
    type: 'document',
    fields: [
      { name: 'id', title: 'ID', type: spec.idKind === 'string' ? 'string' : 'number', readOnly: true,
        hidden: name === 'session' },
      ...Object.entries(spec.fields).map(([n, def]) => field(n, def)),
    ],
    preview: { select: { title: t, subtitle: s } },
  };
});

const banner = `/*
 * GENERATED by scripts/gen-studio-schema.js from src/db/schema.js.
 * Do not edit by hand - change the data model, then run \`npm run studio:schema\`.
 */
`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
// Types the Studio structure leaves out of its lists (bookkeeping).
const hidden = Object.entries(TYPES).filter(([, spec]) => spec.internal).map(([name]) => name);
fs.writeFileSync(
  OUT,
  `${banner}export const hiddenTypes = ${JSON.stringify(hidden)};\n\n` +
    `export default ${JSON.stringify(types, null, 2)};\n`
);
console.log(`wrote ${path.relative(ROOT, OUT)} (${types.length} document types)`);
