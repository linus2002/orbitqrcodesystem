#!/usr/bin/env node
/**
 * Generate src/db/schema.postgres.sql from src/db/schema.sql.
 *
 *   node scripts/gen-pg-schema.js
 *
 * The SQLite schema stays the source of truth - run this after changing it, so
 * the two cannot drift. Only three constructs actually differ; everything else
 * in this schema (TEXT, INTEGER, CHECK, REFERENCES, UNIQUE, partial indexes)
 * is standard SQL that Postgres accepts unchanged.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'db');
const SRC = path.join(DIR, 'schema.sql');
const OUT = path.join(DIR, 'schema.postgres.sql');

const NOW_ISO =
  `to_char(timezone('utc', now()), 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')`;

let sql = fs.readFileSync(SRC, 'utf8');

// 0. PRAGMAs are SQLite-only. Foreign keys are always enforced in Postgres,
//    so the guarantee carries over with nothing to declare.
sql = sql.replace(/^\s*PRAGMA[^;]*;\s*$/gim, '');

// 1. Auto-incrementing primary keys.
sql = sql.replace(
  /INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT/gi,
  'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
);

// 2. The ISO-8601 timestamp default.
sql = sql.replace(
  /strftime\(\s*'%Y-%m-%dT%H:%M:%fZ'\s*,\s*'now'\s*\)/gi,
  NOW_ISO
);

// 3. Case-insensitive email uniqueness. Postgres has no NOCASE collation, so
//    the guarantee moves to a unique index over lower(email) - which is what
//    NOCASE was buying. The application lowercases on the way in regardless.
const hadNocase = /COLLATE\s+NOCASE/i.test(sql);
sql = sql.replace(/\s+COLLATE\s+NOCASE/gi, '');

sql =
  `-- GENERATED FILE - do not edit.\n` +
  `-- Produced from schema.sql by scripts/gen-pg-schema.js; edit that instead.\n\n` +
  sql;

if (hadNocase) {
  sql +=
    `\n-- Replaces SQLite's COLLATE NOCASE on users.email (see the generator).\n` +
    `CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email_lower ON users (lower(email));\n`;
}

fs.writeFileSync(OUT, sql);
console.log(`Wrote ${path.relative(process.cwd(), OUT)} (${sql.split('\n').length} lines)`);
